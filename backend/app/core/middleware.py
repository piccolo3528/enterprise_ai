"""Request ID + timing + last-resort error middleware.

Written as plain ASGI (not Starlette's BaseHTTPMiddleware) so it never buffers a response: the
streaming chat endpoint (M13) sends Server-Sent Events, which must reach the browser as they're
produced.

Unexpected exceptions are turned into the standard 500 JSON *here*, not in an exception handler:
Starlette runs catch-all `Exception` handlers in its outermost layer, after this middleware has
finished, so the response would lose its request ID.
"""

from __future__ import annotations

import json
import logging
import time
import uuid

from starlette.types import ASGIApp, Message, Receive, Scope, Send

from app.core.errors import error_body
from app.core.logging import request_id_var

logger = logging.getLogger("app.request")

REQUEST_ID_HEADER = "X-Request-ID"


class RequestContextMiddleware:
    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":  # lifespan events, websockets
            await self.app(scope, receive, send)
            return

        # Always generated by us. Echoing a client-supplied ID would let anyone write
        # arbitrary text into our logs.
        request_id = uuid.uuid4().hex[:12]
        token = request_id_var.set(request_id)
        started = time.perf_counter()
        status_code = 500  # if the app crashes before sending a response
        response_started = False

        async def send_with_id(message: Message) -> None:
            nonlocal status_code, response_started
            if message["type"] == "http.response.start":
                status_code = message["status"]
                response_started = True
                headers = list(message.get("headers", []))
                headers.append((REQUEST_ID_HEADER.lower().encode(), request_id.encode()))
                message = {**message, "headers": headers}
            await send(message)

        try:
            await self.app(scope, receive, send_with_id)
        except Exception as exc:
            # Full traceback to the server log; a generic message to the client.
            logger.exception("Unhandled error: %s", type(exc).__name__)
            if response_started:
                raise  # half-sent (e.g. a stream): nothing valid left to send, let uvicorn close it
            body = json.dumps(
                error_body("internal_error", "Something went wrong on our side. Please try again.")
            ).encode()
            await send_with_id(
                {
                    "type": "http.response.start",
                    "status": 500,
                    "headers": [(b"content-type", b"application/json")],
                }
            )
            await send_with_id({"type": "http.response.body", "body": body})
        finally:
            elapsed_ms = (time.perf_counter() - started) * 1000
            # Path only: query strings may carry user input we don't want in logs.
            logger.info(
                "%s %s -> %s in %.0f ms", scope["method"], scope["path"], status_code, elapsed_ms
            )
            request_id_var.reset(token)
